def print_summary(results_df: pd.DataFrame) -> None:
    """Print the final summary table with sanity-check comparisons."""
    metrics = ["precision", "recall", "f1", "mcc", "auroc", "accuracy"]

    print("\n" + "=" * 100)
    print("  EXPERIMENT E1 — BASELINE RESULTS SUMMARY")
    print("=" * 100)

    rows = []
    for baseline in results_df["baseline"].unique():
        bdf = results_df[results_df["baseline"] == baseline]
        row = {"Baseline": baseline, "N_folds": len(bdf)}
        for metric in metrics:
            mean_val = bdf[metric].mean()
            std_val = bdf[metric].std()
            row[f"{metric}_mean"] = mean_val
            row[f"{metric}_sd"] = std_val
            row[f"{metric}_str"] = f"{mean_val:.4f} ± {std_val:.4f}"

        # Sanity-check target
        target = SANITY_TARGETS.get(baseline, {})
        target_parts = []
        for m in ["precision", "recall", "f1", "auroc", "accuracy"]:
            tv = target.get(m)
            if tv is not None:
                gap = row[f"{m}_mean"] - tv
                target_parts.append(f"{m}={tv:.3f} (gap={gap:+.4f})")
        row["sanity_check"] = "; ".join(target_parts) if target_parts else "N/A"
        row["source"] = target.get("source", "")
        row["note"] = target.get("note", "")
        rows.append(row)

    summary = pd.DataFrame(rows)

    # Print compact table
    header = (
        f"{'Baseline':<16} {'N':>3}  "
        f"{'Precision':>16}  {'Recall':>16}  {'F1':>16}  "
        f"{'MCC':>16}  {'AUROC':>16}  {'Accuracy':>16}"
    )
    print(header)
    print("-" * len(header))
    for _, r in summary.iterrows():
        print(
            f"{r['Baseline']:<16} {r['N_folds']:>3}  "
            f"{r['precision_str']:>16}  {r['recall_str']:>16}  {r['f1_str']:>16}  "
            f"{r['mcc_str']:>16}  {r['auroc_str']:>16}  {r['accuracy_str']:>16}"
        )

    print("\n  Sanity-check comparisons vs. published results:")
    print("  " + "-" * 90)
    for _, r in summary.iterrows():
        if r["sanity_check"] != "N/A":
            print(f"  {r['Baseline']:<16} {r['source']}")
            print(f"  {'':16} Target: {r['sanity_check']}")
            print(f"  {'':16} Note: {r['note']}")
            print()


def parse_args() -> argparse.Namespace:
    """Parse command-line arguments."""
    parser = argparse.ArgumentParser(
        description="E1 baselines (resumable, incremental save)"
    )
    parser.add_argument(
        "--only",
        choices=["b1", "b2", "b3"],
        default=None,
        help="Run only the specified baseline group",
    )
    parser.add_argument(
        "--time-one-fold",
        action="store_true",
        help="Time one fold of each selected baseline, print estimate, then exit",
    )
    return parser.parse_args()


def main() -> None:
    """Run all baselines and produce the summary table."""
    args = parse_args()
    cfg = load_config()
    df, splits = load_data_and_splits()

    print(f"[INFO] Dataset: {len(df):,} rows, "
          f"fraud rate: {df[TARGET].mean()*100:.2f}%")
    print(f"[INFO] Splits: {len(splits['train_cv'])} seed repeats x "
          f"{len(list(splits['train_cv'].values())[0])} folds = "
          f"{sum(len(f) for f in splits['train_cv'].values())} fold assignments")

    # Load already-completed folds for resume
    done = load_done(RESULTS_CSV)
    if done:
        print(f"[INFO] Resuming: {len(done)} fold(s) already in CSV, will skip them")

    # Determine which baselines to run
    run_b1_flag = args.only is None or args.only == "b1"
    run_b2_flag = args.only is None or args.only == "b2"
    run_b3_flag = args.only is None or args.only == "b3"

    # Limit to 1 fold per baseline in timing mode
    fold_limit = 1 if args.time_one_fold else None

    timings: dict[str, float] = {}
    all_results: list[dict] = []

    # --- B1: Random Forest + BoW ---
    if run_b1_flag:
        print("\n" + "=" * 60)
        print("  B1 — Random Forest + BoW (Vidros et al. 2017)")
        print("=" * 60)
        t0 = time.perf_counter()
        res = run_b1(df, splits, cfg, done, limit=fold_limit)
        timings["B1"] = time.perf_counter() - t0 if res else 0
        all_results.extend(res)

    # --- B2: TF-IDF + GBM ---
    if run_b2_flag:
        print("\n" + "=" * 60)
        print("  B2 — TF-IDF + Gradient Boosting (Naudé et al. 2023)")
        print("=" * 60)
        t0 = time.perf_counter()
        res = run_b2(df, splits, cfg, done, limit=fold_limit)
        timings["B2"] = time.perf_counter() - t0 if res else 0
        all_results.extend(res)

    # --- B3: Bi-LSTM + LightGBM ---
    if run_b3_flag:
        print("\n" + "=" * 60)
        print("  B3 — Bi-LSTM (Pillai 2023) — 5 folds only")
        print("=" * 60)
        t0 = time.perf_counter()
        res = run_b3_bilstm(df, splits, cfg, done, limit=fold_limit)
        timings["B3_BiLSTM"] = time.perf_counter() - t0 if res else 0
        all_results.extend(res)

        print("\n" + "=" * 60)
        print("  B3 — LightGBM (Pillai 2023 comparison) — 5 folds")
        print("=" * 60)
        t0 = time.perf_counter()
        res = run_b3_lgbm(df, splits, cfg, done, limit=fold_limit)
        timings["B3_LightGBM"] = time.perf_counter() - t0 if res else 0
        all_results.extend(res)

    # --- Timing estimate mode ---
    if args.time_one_fold:
        print("\n" + "=" * 60)
        print("  TIMING ESTIMATE (one fold each)")
        print("=" * 60)
        for label, t in timings.items():
            if label in ("B1", "B2"):
                total_folds = 25
            else:
                total_folds = 5
            est = t * total_folds
            print(f"  {label}: {t:.1f}s/fold × {total_folds} folds ≈ {est/60:.1f} min")
        total_est = sum(
            t * (25 if k in ("B1", "B2") else 5)
            for k, t in timings.items()
        )
        print(f"  TOTAL estimated: {total_est/60:.1f} min")
        print("\n[INFO] --time-one-fold complete. Results from timing folds saved to CSV.")
        return

    # --- Summary table (full run or --only) ---
    if RESULTS_CSV.exists():
        results_df = pd.read_csv(RESULTS_CSV)
        print(f"\n[OK] {len(results_df)} total fold results in {RESULTS_CSV}")
        print_summary(results_df)
    elif all_results:
        results_df = pd.DataFrame(all_results)
        print_summary(results_df)


if __name__ == "__main__":
    main()

