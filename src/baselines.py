TEXT_FIELDS = ["title", "company_profile", "description", "requirements", "benefits"]

# Rule-set / structured features
# Binary indicators
BINARY_FEATURES = [
    "telecommuting",
    "has_company_logo",
    "has_questions",
    "has_salary_range",
    "company_profile_missing",
    "description_missing",
    "requirements_missing",
    "benefits_missing",
]
# Categoricals to one-hot encode
CATEGORICAL_FEATURES = [
    "employment_type",
    "required_experience",
    "required_education",
]

TARGET = "fraudulent"

# Column order for the results CSV
COL_ORDER = ["baseline", "seed", "fold", "precision", "recall", "f1",
             "mcc", "auroc", "accuracy"]


# ===================================================================
# Resumability helpers
# ===================================================================
def load_done(csv_path: Path) -> set[tuple[str, str, str]]:
    """Return set of (baseline, seed, fold) already saved in the CSV."""
    if not csv_path.exists():
        return set()
    try:
        existing = pd.read_csv(csv_path)
        return set(
            zip(existing["baseline"], existing["seed"], existing["fold"])
        )
    except Exception:
        return set()


def append_result(row: dict, csv_path: Path) -> None:
    """Append a single result row to the CSV (create with header if new)."""
    write_header = not csv_path.exists()
    row_df = pd.DataFrame([row])[COL_ORDER]
    row_df.to_csv(csv_path, mode="a", header=write_header, index=False)


