# B2 — TF-IDF + Gradient Boosting (Naudé et al. 2023)
# ===================================================================
def run_b2(df: pd.DataFrame, splits: dict, cfg: dict,
           done: set, *, limit: int | None = None) -> list[dict]:
    """
    Replicates Naudé et al. (2023): TfidfVectorizer (max_features=5000)
    + GradientBoostingClassifier.

    Sanity-check target: F1 ≈ 0.883 (Naudé et al. Table 9).
    """
    results = []
    train_cv = splits["train_cv"]
    count = 0

    for seed_key, folds in train_cv.items():
        for fold_key, indices in folds.items():
            if ("B2_TFIDF_GBM", seed_key, fold_key) in done:
                print(f"  [B2] {seed_key}/{fold_key}  SKIPPED (already done)")
                continue
            if limit is not None and count >= limit:
                return results

            t0 = time.perf_counter()
            train_idx = indices["train"]
            val_idx = indices["val"]

            df_train = df.iloc[train_idx].reset_index(drop=True)
            df_val = df.iloc[val_idx].reset_index(drop=True)
            y_train = df_train[TARGET].values
            y_val = df_val[TARGET].values

            # Text features: TF-IDF
            tfidf = TfidfVectorizer(max_features=5000)
            X_text_train = tfidf.fit_transform(concat_text(df_train))
            X_text_val = tfidf.transform(concat_text(df_val))

            # Structured features
            X_struct_train, X_struct_val, _ = build_structured_features(df_train, df_val)

            # Combine (GBM needs dense for reasonable speed with 5k features)
            X_train = sparse_hstack([X_text_train, X_struct_train]).tocsr()
            X_val = sparse_hstack([X_text_val, X_struct_val]).tocsr()

            # Model — sklearn GradientBoostingClassifier does NOT support n_jobs
            clf = GradientBoostingClassifier(
                n_estimators=200,
                max_depth=5,
                learning_rate=0.1,
                random_state=cfg["random_seed"],
            )
            clf.fit(X_train.toarray(), y_train)
            y_pred = clf.predict(X_val.toarray())
            y_prob = clf.predict_proba(X_val.toarray())[:, 1]

            elapsed = time.perf_counter() - t0
            m = compute_metrics(y_val, y_pred, y_prob)
            m.update({"baseline": "B2_TFIDF_GBM", "seed": seed_key, "fold": fold_key})
            results.append(m)
            append_result(m, RESULTS_CSV)
            count += 1
            print(f"  [B2] {seed_key}/{fold_key}  "
                  f"F1={m['f1']:.4f}  AUROC={m['auroc']:.4f}  ({elapsed:.1f}s)")

    return results


# ===================================================================
# B3 — Bi-LSTM + LightGBM ensemble comparison (Pillai 2023)
# ===================================================================
#
# COMPUTE-BUDGET DECISION (Assignment 2 Part M fallback plan):
# Bi-LSTM is run on only 5 fold assignments (one fold per seed repeat:
# seed_0/fold_0 .. seed_4/fold_0) instead of all 25, to keep training
# time within our GPU-free compute budget.  LightGBM is run on the same
# 5 folds for a direct comparison.

B3_FOLDS = [
    ("seed_0", "fold_0"),
    ("seed_1", "fold_0"),
    ("seed_2", "fold_0"),
    ("seed_3", "fold_0"),
    ("seed_4", "fold_0"),
]


def _build_bilstm_model(
    vocab_sizes: dict[str, int],
    max_lengths: dict[str, int],
    n_struct_features: int,
    embedding_dim: int = 64,
    lstm_units: int = 64,
) -> "tf.keras.Model":
    """
    Build a multi-branch Bi-LSTM matching Pillai (2023):
    5 text branches (title, company_profile, description, benefits,
    requirements) each with Embedding → Bidirectional LSTM, concatenated
    with structured features, then Dense → sigmoid.
    """
    import tensorflow as tf
    from tensorflow.keras import layers, Model

    text_inputs = []
    text_branches = []

    for field in TEXT_FIELDS:
        inp = layers.Input(shape=(max_lengths[field],), name=f"input_{field}")
        text_inputs.append(inp)
        x = layers.Embedding(
            input_dim=vocab_sizes[field] + 1,
            output_dim=embedding_dim,
            mask_zero=True,
            name=f"embed_{field}",
        )(inp)
        x = layers.Bidirectional(
            layers.LSTM(lstm_units, name=f"lstm_{field}"),
            name=f"bilstm_{field}",
        )(x)
        text_branches.append(x)

    # Structured features input
    struct_input = layers.Input(shape=(n_struct_features,), name="input_struct")

    # Concatenate all branches
    merged = layers.Concatenate(name="concat")(text_branches + [struct_input])
    x = layers.Dense(128, activation="relu", name="dense_1")(merged)
    x = layers.Dropout(0.3, name="dropout_1")(x)
    x = layers.Dense(64, activation="relu", name="dense_2")(x)
    x = layers.Dropout(0.2, name="dropout_2")(x)
    output = layers.Dense(1, activation="sigmoid", name="output")(x)

    model = Model(inputs=text_inputs + [struct_input], outputs=output)
    model.compile(
        optimizer="adam",
        loss="binary_crossentropy",
        metrics=["accuracy"],
    )
    return model


def _tokenize_texts(
    df_train: pd.DataFrame,
    df_val: pd.DataFrame,
    max_vocab: int = 5000,
    max_len: int = 200,
) -> tuple[dict, dict, dict, dict]:
    """
    Tokenize each text field independently using Keras Tokenizer.
    Returns (train_seqs, val_seqs, vocab_sizes, max_lengths) dicts keyed
    by field name.
    """
    from tensorflow.keras.preprocessing.text import Tokenizer
    from tensorflow.keras.preprocessing.sequence import pad_sequences

    train_seqs = {}
    val_seqs = {}
    vocab_sizes = {}
    max_lengths = {}

    for field in TEXT_FIELDS:
        tok = Tokenizer(num_words=max_vocab, oov_token="<OOV>")
        tok.fit_on_texts(df_train[field].fillna("").values)

        tr_seq = pad_sequences(
            tok.texts_to_sequences(df_train[field].fillna("").values),
            maxlen=max_len, padding="post", truncating="post",
        )
        va_seq = pad_sequences(
            tok.texts_to_sequences(df_val[field].fillna("").values),
            maxlen=max_len, padding="post", truncating="post",
        )

        train_seqs[field] = tr_seq
        val_seqs[field] = va_seq
        vocab_sizes[field] = min(max_vocab, len(tok.word_index))
        max_lengths[field] = max_len

    return train_seqs, val_seqs, vocab_sizes, max_lengths


def run_b3_bilstm(df: pd.DataFrame, splits: dict, cfg: dict,
                  done: set, *, limit: int | None = None) -> list[dict]:
    """
    Bi-LSTM multi-branch model replicating Pillai (2023).
    Run on 5 folds only (compute-budget decision).
    Sanity-check target: AUROC ≈ 0.91, accuracy ≈ 98.71%.
    """
    # Delay TF import so B1/B2 don't pay the startup cost
    os.environ["TF_CPP_MIN_LOG_LEVEL"] = "3"
    import tensorflow as tf
    tf.get_logger().setLevel("ERROR")

    results = []
    train_cv = splits["train_cv"]
    count = 0

    for seed_key, fold_key in B3_FOLDS:
        if ("B3_BiLSTM", seed_key, fold_key) in done:
            print(f"  [B3-BiLSTM] {seed_key}/{fold_key}  SKIPPED (already done)")
            continue
        if limit is not None and count >= limit:
            return results

        t0 = time.perf_counter()
        indices = train_cv[seed_key][fold_key]
        train_idx = indices["train"]
        val_idx = indices["val"]

        df_train = df.iloc[train_idx].reset_index(drop=True)
        df_val = df.iloc[val_idx].reset_index(drop=True)
        y_train = df_train[TARGET].values
        y_val = df_val[TARGET].values

        # Tokenize each text branch independently
        train_seqs, val_seqs, vocab_sizes, max_lengths = _tokenize_texts(
            df_train, df_val
        )

        # Structured features (dense)
        X_struct_train, X_struct_val, _ = build_structured_features(df_train, df_val)
        X_struct_train_dense = X_struct_train.toarray().astype(np.float32)
        X_struct_val_dense = X_struct_val.toarray().astype(np.float32)
        n_struct = X_struct_train_dense.shape[1]

        # Build model
        tf.keras.backend.clear_session()
        tf.random.set_seed(cfg["random_seed"])
        model = _build_bilstm_model(vocab_sizes, max_lengths, n_struct)

        # Compute class weight for imbalanced data
        n_pos = y_train.sum()
        n_neg = len(y_train) - n_pos
        class_weight = {0: 1.0, 1: n_neg / max(n_pos, 1)}

        # Train inputs
        train_inputs = [train_seqs[f] for f in TEXT_FIELDS] + [X_struct_train_dense]
        val_inputs = [val_seqs[f] for f in TEXT_FIELDS] + [X_struct_val_dense]

        model.fit(
            train_inputs,
            y_train,
            epochs=10,
            batch_size=64,
            class_weight=class_weight,
            validation_data=(val_inputs, y_val),
            verbose=0,
        )

        y_prob = model.predict(val_inputs, verbose=0).ravel()
        y_pred = (y_prob >= 0.5).astype(int)

        elapsed = time.perf_counter() - t0
        m = compute_metrics(y_val, y_pred, y_prob)
        m.update({"baseline": "B3_BiLSTM", "seed": seed_key, "fold": fold_key})
        results.append(m)
        append_result(m, RESULTS_CSV)
        count += 1
        print(f"  [B3-BiLSTM] {seed_key}/{fold_key}  "
              f"F1={m['f1']:.4f}  AUROC={m['auroc']:.4f}  Acc={m['accuracy']:.4f}  ({elapsed:.1f}s)")

    return results


def run_b3_lgbm(df: pd.DataFrame, splits: dict, cfg: dict,
                done: set, *, limit: int | None = None) -> list[dict]:
    """
    LightGBM baseline on same features as B1/B2, run on the same 5 folds
    as Bi-LSTM for direct ensemble comparison (Pillai 2023).
    """
    import lightgbm as lgb

    results = []
    train_cv = splits["train_cv"]
    count = 0

    for seed_key, fold_key in B3_FOLDS:
        if ("B3_LightGBM", seed_key, fold_key) in done:
            print(f"  [B3-LGBM]   {seed_key}/{fold_key}  SKIPPED (already done)")
            continue
        if limit is not None and count >= limit:
            return results

        t0 = time.perf_counter()
        indices = train_cv[seed_key][fold_key]
        train_idx = indices["train"]
        val_idx = indices["val"]

        df_train = df.iloc[train_idx].reset_index(drop=True)
        df_val = df.iloc[val_idx].reset_index(drop=True)
        y_train = df_train[TARGET].values
        y_val = df_val[TARGET].values

        # Text features: TF-IDF (same as B2)
        tfidf = TfidfVectorizer(max_features=5000)
        X_text_train = tfidf.fit_transform(concat_text(df_train))
        X_text_val = tfidf.transform(concat_text(df_val))

        # Structured features
        X_struct_train, X_struct_val, _ = build_structured_features(df_train, df_val)

        X_train = sparse_hstack([X_text_train, X_struct_train]).tocsr()
        X_val = sparse_hstack([X_text_val, X_struct_val]).tocsr()

        # Compute scale_pos_weight for imbalanced data
        n_pos = y_train.sum()
        n_neg = len(y_train) - n_pos
        spw = n_neg / max(n_pos, 1)

        clf = lgb.LGBMClassifier(
            n_estimators=300,
            max_depth=7,
            learning_rate=0.1,
            scale_pos_weight=spw,
            random_state=cfg["random_seed"],
            verbose=-1,
            n_jobs=-1,
        )
        clf.fit(X_train, y_train)
        y_pred = clf.predict(X_val)
        y_prob = clf.predict_proba(X_val)[:, 1]

        elapsed = time.perf_counter() - t0
        m = compute_metrics(y_val, y_pred, y_prob)
        m.update({"baseline": "B3_LightGBM", "seed": seed_key, "fold": fold_key})
        results.append(m)
        append_result(m, RESULTS_CSV)
        count += 1
        print(f"  [B3-LGBM]   {seed_key}/{fold_key}  "
              f"F1={m['f1']:.4f}  AUROC={m['auroc']:.4f}  Acc={m['accuracy']:.4f}  ({elapsed:.1f}s)")

    return results


