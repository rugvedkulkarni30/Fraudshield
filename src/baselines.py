# Helpers
# ===================================================================
def load_config() -> dict:
    """Load configs/seeds.yaml."""
    with open(SEEDS_YAML, "r", encoding="utf-8") as f:
        return yaml.safe_load(f)


def load_data_and_splits() -> tuple[pd.DataFrame, dict]:
    """Load the cleaned CSV and the pre-computed split indices."""
    df = pd.read_csv(CLEAN_CSV)
    with open(SPLITS_JSON, "r", encoding="utf-8") as f:
        splits = json.load(f)
    return df, splits


def concat_text(df: pd.DataFrame) -> pd.Series:
    """Concatenate text fields into a single string per row."""
    return df[TEXT_FIELDS].fillna("").agg(" ".join, axis=1)


def build_structured_features(
    df_train: pd.DataFrame,
    df_val: pd.DataFrame,
) -> tuple[np.ndarray, np.ndarray, OneHotEncoder]:
    """
    Build the structured feature matrix (binary + one-hot categoricals).
    Returns (X_struct_train, X_struct_val, fitted_encoder).
    """
    ohe = OneHotEncoder(handle_unknown="ignore", sparse_output=True)
    cat_train = ohe.fit_transform(df_train[CATEGORICAL_FEATURES])
    cat_val = ohe.transform(df_val[CATEGORICAL_FEATURES])

    bin_train = df_train[BINARY_FEATURES].values.astype(np.float64)
    bin_val = df_val[BINARY_FEATURES].values.astype(np.float64)

    from scipy.sparse import csr_matrix
    struct_train = sparse_hstack([csr_matrix(bin_train), cat_train]).tocsr()
    struct_val = sparse_hstack([csr_matrix(bin_val), cat_val]).tocsr()

    return struct_train, struct_val, ohe


def compute_metrics(y_true: np.ndarray, y_pred: np.ndarray, y_prob: np.ndarray) -> dict:
    """Compute fraud-class precision, recall, F1, MCC, AUROC, accuracy."""
    return {
        "precision": precision_score(y_true, y_pred, zero_division=0),
        "recall": recall_score(y_true, y_pred, zero_division=0),
        "f1": f1_score(y_true, y_pred, zero_division=0),
        "mcc": matthews_corrcoef(y_true, y_pred),
        "auroc": roc_auc_score(y_true, y_prob) if len(np.unique(y_true)) > 1 else 0.0,
        "accuracy": accuracy_score(y_true, y_pred),
    }


# ===================================================================
# B1 — Random Forest + BoW + rule-set (Vidros et al. 2017)
# ===================================================================
def run_b1(df: pd.DataFrame, splits: dict, cfg: dict,
           done: set, *, limit: int | None = None) -> list[dict]:
    """
    Replicates Vidros et al. (2017): Random Forest on CountVectorizer
    bag-of-words (max_features=5000) + structured rule-set features.

    Sanity-check target: precision ≈ 0.91, recall ≈ 0.91
    (Vidros et al. Table 4, balanced setup — our setup is imbalanced).
    """
    results = []
    train_cv = splits["train_cv"]
    count = 0

    for seed_key, folds in train_cv.items():
        for fold_key, indices in folds.items():
            if ("B1_RF_BoW", seed_key, fold_key) in done:
                print(f"  [B1] {seed_key}/{fold_key}  SKIPPED (already done)")
                continue
            if limit is not None and count >= limit:
                return results

            t0 = time.perf_counter()
            train_idx = indices["train"]
            val_idx = indices["val"]

            df_train = df.iloc[train_idx].reset_index(drop=True)
            df_val = df.iloc[val_idx].reset_index(drop=True)
            y_train = df_train[TARGET].values
            y_val = df_val[TARGET].values

            # Text features: bag-of-words
            bow = CountVectorizer(max_features=5000)
            X_text_train = bow.fit_transform(concat_text(df_train))
            X_text_val = bow.transform(concat_text(df_val))

            # Structured features
            X_struct_train, X_struct_val, _ = build_structured_features(df_train, df_val)

            # Combine
            X_train = sparse_hstack([X_text_train, X_struct_train]).tocsr()
            X_val = sparse_hstack([X_text_val, X_struct_val]).tocsr()

            # Model
            clf = RandomForestClassifier(
                n_estimators=100,
                random_state=cfg["random_seed"],
                n_jobs=-1,
            )
            clf.fit(X_train, y_train)
            y_pred = clf.predict(X_val)
            y_prob = clf.predict_proba(X_val)[:, 1]

            elapsed = time.perf_counter() - t0
            m = compute_metrics(y_val, y_pred, y_prob)
            m.update({"baseline": "B1_RF_BoW", "seed": seed_key, "fold": fold_key})
            results.append(m)
            append_result(m, RESULTS_CSV)
            count += 1
            print(f"  [B1] {seed_key}/{fold_key}  "
                  f"F1={m['f1']:.4f}  AUROC={m['auroc']:.4f}  ({elapsed:.1f}s)")

    return results


