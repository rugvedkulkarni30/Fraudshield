"""
baselines.py — Experiment E1 (Assignment 2 Part H)
====================================================
Three baseline replications for the EMSCAD fraud detection dataset.

B1 — Random Forest + BoW + rule-set       (Vidros et al. 2017)
B2 — TF-IDF + Gradient Boosting           (Naudé et al. 2023)
B3 — Bi-LSTM + LightGBM ensemble          (Pillai 2023)

All CV fold assignments are read from data/processed/splits.json
(generated by splits.py). Seeds are read from configs/seeds.yaml.

Per-fold results are saved to data/processed/e1_baseline_results.csv.

Usage:
    python src/baselines.py                  # run all baselines
    python src/baselines.py --only b1        # run only B1
    python src/baselines.py --only b2        # run only B2
    python src/baselines.py --only b3        # run only B3 (BiLSTM + LightGBM)
    python src/baselines.py --time-one-fold  # time one fold per baseline, print estimate

Results are appended per-fold, so the script is resumable: any
(baseline, seed, fold) already present in the CSV is skipped.
"""

